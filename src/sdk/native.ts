import {
  allowedNativeHeader,
  decodeControl,
  encodeControl,
  HEADER_PROFILE,
  validateHeaderPairs,
} from "../public/headers.js";
import {
  type CapabilityDefinition,
  type CapabilityRef,
  capabilityRefSchema,
  opaqueId,
} from "../public/schemas.js";
import { ClientHttp, ProtocolError } from "./http.js";

export type HeaderProfile = typeof HEADER_PROFILE;
export { encodeControl } from "../public/headers.js";
export type NativeHeaders = Headers | readonly (readonly [string, string])[];
export type NativeBody = string | Uint8Array | Blob | FormData;
export type ProxyRequest = {
  providerRegistrationId: string;
  endpoint: string;
  connectionId?: string;
  method: "GET" | "HEAD" | "POST" | "PUT" | "PATCH" | "DELETE" | "OPTIONS";
  path: string;
  query?: URLSearchParams;
  headers?: NativeHeaders;
  body?: NativeBody;
};
export type CapabilityInvocation = { capability: CapabilityRef; connectionId?: string } & (
  | { input: unknown; body?: never; headers?: never }
  | { body?: NativeBody; headers?: NativeHeaders; input?: never }
);
export function nativeHeaderPairs(
  input: NativeHeaders | undefined,
  response = false,
): [string, string][] {
  const pairs = validateHeaderPairs(
    input instanceof Headers ? [...input.entries()] : (input ?? []),
  );
  for (const [name] of pairs) {
    // Representation lengths are legitimate response metadata, never request-controlled framing.
    if (response && name === "content-length") continue;
    if (
      !allowedNativeHeader(name) ||
      (!response &&
        (name === "forwarded" ||
          name.startsWith("x-forwarded-") ||
          name === "origin" ||
          name === "referer" ||
          name.startsWith("sec-")))
    )
      throw new TypeError("Reserved native header");
  }
  return pairs;
}
export async function decodeNativeResponse(
  response: Response,
  route: "proxy" | "invoke",
  nativeMethod: string,
  headCarrier = false,
): Promise<Response> {
  const raw = response.headers.get("X-Integration-Response-Metadata");
  if (raw === null) return response;
  try {
    const origin = response.headers.get("X-Integration-Origin");
    if (
      response.status !== 200 ||
      !(origin === "provider" || (route === "invoke" && origin === "service"))
    )
      throw new ProtocolError("Response carrier has invalid route provenance");
    const meta = decodeControl(raw);
    if (
      !meta ||
      typeof meta !== "object" ||
      Array.isArray(meta) ||
      Object.keys(meta).sort().join(",") !== "headers,status,version" ||
      !("version" in meta) ||
      meta.version !== 1 ||
      !("status" in meta) ||
      typeof meta.status !== "number" ||
      !Number.isInteger(meta.status) ||
      meta.status < 200 ||
      meta.status > 599 ||
      !("headers" in meta) ||
      !Array.isArray(meta.headers) ||
      !meta.headers.every(
        (pair: unknown) =>
          Array.isArray(pair) && pair.length === 2 && pair.every((v) => typeof v === "string"),
      )
    )
      throw new ProtocolError("Invalid response carrier metadata");
    if (!(route === "proxy" && headCarrier) && (meta.status < 300 || meta.status > 399))
      throw new ProtocolError("Response status is not eligible for this carrier");
    const headers = new Headers(nativeHeaderPairs(meta.headers, true));
    headers.set("X-Integration-Origin", origin!);
    const nullBody = nativeMethod === "HEAD" || [204, 205, 304].includes(meta.status);
    if (
      nullBody &&
      (response.headers.has("Content-Encoding") ||
        (response.headers.has("Content-Length") && response.headers.get("Content-Length") !== "0"))
    )
      throw new ProtocolError("Bodyless response carrier has payload framing");
    if (nullBody) await response.body?.cancel();
    return new Response(nullBody ? null : response.body, { status: meta.status, headers });
  } catch (error) {
    await response.body?.cancel().catch(() => {});
    throw error instanceof ProtocolError
      ? error
      : new ProtocolError("Invalid native response carrier");
  }
}

export class NativeClient {
  #capabilities: readonly CapabilityDefinition[] = [];
  constructor(private readonly http: ClientHttp) {}
  setCapabilities(definitions: readonly CapabilityDefinition[]): void {
    this.#capabilities = definitions;
  }
  #headers(
    headers: NativeHeaders | undefined,
    body: NativeBody | undefined,
    connectionId: string | undefined,
  ): Headers {
    const pairs = nativeHeaderPairs(headers);
    if (body instanceof FormData && pairs.some(([name]) => name.toLowerCase() === "content-type"))
      throw new TypeError("FormData Content-Type must be generated by the browser");
    const physical = new Headers({ "X-Integration-Request-Headers": encodeControl(pairs) });
    if (connectionId !== undefined)
      physical.set("X-Integration-Connection", opaqueId.parse(connectionId));
    return physical;
  }
  async request(request: ProxyRequest, options: { signal?: AbortSignal } = {}): Promise<Response> {
    opaqueId.parse(request.providerRegistrationId);
    opaqueId.parse(request.endpoint);
    if (!["GET", "HEAD", "POST", "PUT", "PATCH", "DELETE", "OPTIONS"].includes(request.method))
      throw new TypeError("Unsupported native method");
    if (
      !request.path.startsWith("/") ||
      request.path.startsWith("//") ||
      /[?#\\\x00-\x20]/.test(request.path) ||
      request.path.split("/").some((segment) => [".", ".."].includes(decodeURIComponent(segment)))
    )
      throw new TypeError("Expected a native absolute path without query or traversal");
    const headers = this.#headers(request.headers, request.body, request.connectionId);
    const carrier = ["GET", "HEAD"].includes(request.method) && request.body !== undefined;
    if (carrier) headers.set("X-Integration-Method", request.method);
    const path = `${this.http.appPath}/proxy/${encodeURIComponent(request.providerRegistrationId)}/${encodeURIComponent(request.endpoint)}${request.path}${request.query?.size ? `?${request.query}` : ""}`;
    const response = await this.http.fetch(path, {
      method: carrier ? "POST" : request.method,
      headers,
      ...(request.body !== undefined ? { body: request.body as BodyInit } : {}),
      ...options,
    });
    return decodeNativeResponse(
      response,
      "proxy",
      request.method,
      carrier && request.method === "HEAD",
    );
  }
  async invoke(
    invocation: CapabilityInvocation,
    options: { signal?: AbortSignal } = {},
  ): Promise<Response> {
    const ref = capabilityRefSchema.parse(invocation.capability);
    const definition = this.#capabilities.find(
      (item) => item.ref.id === ref.id && item.ref.version === ref.version,
    );
    if (!definition?.http)
      throw new TypeError("Capability has no supported HTTP entrypoint; refresh discovery");
    const isJson = Object.hasOwn(invocation, "input");
    if ((definition.http.input.kind === "json") !== isJson)
      throw new TypeError("Invocation does not match its declared input mode");
    if (isJson && (Object.hasOwn(invocation, "body") || Object.hasOwn(invocation, "headers")))
      throw new TypeError("Choose JSON arguments or a native body");
    const body = isJson ? JSON.stringify(invocation.input) : invocation.body;
    if (isJson && body === undefined) throw new TypeError("JSON input is required");
    const headers = this.#headers(
      isJson ? [["Content-Type", "application/json"]] : invocation.headers,
      body,
      invocation.connectionId,
    );
    if (isJson) headers.set("Content-Type", "application/json");
    const response = await this.http.fetch(
      `${this.http.appPath}/capabilities/${encodeURIComponent(ref.id)}/versions/${ref.version}/invoke`,
      {
        method: "POST",
        headers,
        ...(body !== undefined ? { body: body as BodyInit } : {}),
        ...options,
      },
    );
    return decodeNativeResponse(response, "invoke", "POST");
  }
}
